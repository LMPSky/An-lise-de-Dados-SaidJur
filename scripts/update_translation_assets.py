def _escape(text: str) -> str:
    return text.replace('\\', '\\\\').replace("'", "\\'")


def _parse_dict_node(text: str) -> ast.Dict:
    module = ast.parse(text)
    for node in module.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == 'TRADUCOES_COLUNAS'
            for target in node.targets
        ):
            if isinstance(node.value, ast.Dict):
                return node.value
    raise RuntimeError('TRADUCOES_COLUNAS não encontrado')


def _literal_keys(text: str) -> list[str]:
    dict_node = _parse_dict_node(text)
    return [
        key.value
        for key in dict_node.keys
        if isinstance(key, ast.Constant) and isinstance(key.value, str)
    ]


def _section_insert_index(lines: list[str], label: str) -> int:
    section_index = next(i for i, line in enumerate(lines) if label in line)
    next_section_index = None
    for i in range(section_index + 1, len(lines)):
        if lines[i].startswith('    # ──') or lines[i].strip() == '}':
            next_section_index = i
            break
    if next_section_index is None:
        raise RuntimeError(f'Seção seguinte não encontrada para {label}')
    if next_section_index > 0 and lines[next_section_index - 1].strip() == '':
        return next_section_index - 1
    return next_section_index


def _anchor_insert_index(lines: list[str], anchor: str) -> int:
    anchor_index = next(i for i, line in enumerate(lines) if anchor in line)
    return anchor_index


def atualizar_traducoes() -> None:
    original_text = TRADUCOES_PATH.read_text(encoding='utf-8')
    lines = original_text.splitlines(keepends=True)

    existing_keys = set(_literal_keys(original_text))
    planned_keys: set[str] = set()

    for spec in SECTION_SPECS:
        entries_to_add: list[tuple[str, str]] = []
        for key, value in spec['entries']:
            if key in existing_keys or key in planned_keys:
                continue
            planned_keys.add(key)
            entries_to_add.append((key, value))

        if not entries_to_add:
            continue

        block = [f"    '{_escape(key)}': '{_escape(value)}',\n" for key, value in entries_to_add]

        if spec['kind'] == 'existing':
            insert_at = _section_insert_index(lines, spec['label'])
            lines[insert_at:insert_at] = block
        else:
            insert_at = _anchor_insert_index(lines, spec['anchor'])
            lines[insert_at:insert_at] = [spec['comment'], *block, '\n']

    updated_text = ''.join(lines)
    TRADUCOES_PATH.write_text(updated_text, encoding='utf-8')

    final_keys = _literal_keys(updated_text)
    duplicates = sorted(key for key, count in Counter(final_keys).items() if count > 1)
    if duplicates:
        raise RuntimeError(f'Chaves duplicadas encontradas: {duplicates}')


def escrever_dicionarios() -> None:
    content = (
        '# Dicionário de tradução de valores de ENUM/código.\n'
        '# Estrutura: <tabela>: <coluna>: <valor>: <tradução>\n\n'
    )
    content += yaml.safe_dump(
        DICIONARIOS,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
    )
    DICIONARIOS_PATH.write_text(content, encoding='utf-8')
    yaml.safe_load(DICIONARIOS_PATH.read_text(encoding='utf-8'))


if __name__ == '__main__':
    atualizar_traducoes()
    escrever_dicionarios()
